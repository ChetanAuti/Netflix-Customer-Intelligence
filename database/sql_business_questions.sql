-- Q16. Using RANK(), rank subscription plans by total revenue generated (monthly_price × count of active subscriptions).
SELECT
    sp.plan_name,
    SUM(s.monthly_price) AS total_revenue,
    RANK() OVER (
        ORDER BY SUM(s.monthly_price) DESC
    ) AS revenue_rank
FROM subscriptions s
JOIN subscription_plans sp
    ON s.plan_id = sp.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY sp.plan_name;

-- Q17. For each customer, use ROW_NUMBER() to identify their most recent support ticket and return only that row.
WITH ranked_tickets AS (
    SELECT
        st.*,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY ticket_date DESC NULLS LAST
        ) AS rn
    FROM support_tickets st
)
SELECT *
FROM ranked_tickets
WHERE rn = 1;

-- Q18. Calculate a 3-month moving average of new customer registrations using a window function.
WITH monthly_registrations AS (
    SELECT
        DATE_TRUNC('month', registration_date)::date AS month,
        COUNT(*) AS new_customers
    FROM customers
    GROUP BY month
)
SELECT
    month,
    new_customers,
    ROUND(
        AVG(new_customers) OVER (
            ORDER BY month
            ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
        ),
        2
    ) AS three_month_moving_average
FROM monthly_registrations
ORDER BY month;

-- Q19. Using LAG(), identify customers whose monthly watch time in the most recent month is lower than their watch time in the prior month.
WITH monthly_watch AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', viewing_date)::date AS month,
        SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY customer_id, month
),
with_previous AS (
    SELECT
        *,
        LAG(watch_minutes) OVER (
            PARTITION BY customer_id
            ORDER BY month
        ) AS previous_month_watch
    FROM monthly_watch
)
SELECT *
FROM with_previous
WHERE month = (SELECT MAX(month) FROM monthly_watch)
  AND watch_minutes < previous_month_watch;

-- Q20. Build a customer acquisition cohort analysis: percentage of each cohort still active at 1, 3, and 6 months after registration.
WITH cohorts AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', registration_date)::date AS cohort_month
    FROM customers
),
cohort_activity AS (
    SELECT
        c.cohort_month,
        COUNT(*) AS cohort_size,
        COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM subscriptions s
                WHERE s.customer_id = c.customer_id
                  AND s.subscription_start_date
                      <= c.cohort_month + INTERVAL '1 month'
                  AND (
                      s.subscription_end_date IS NULL
                      OR s.subscription_end_date
                         >= c.cohort_month + INTERVAL '1 month'
                  )
            )
        ) AS active_1_month,
        COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM subscriptions s
                WHERE s.customer_id = c.customer_id
                  AND s.subscription_start_date
                      <= c.cohort_month + INTERVAL '3 months'
                  AND (
                      s.subscription_end_date IS NULL
                      OR s.subscription_end_date
                         >= c.cohort_month + INTERVAL '3 months'
                  )
            )
        ) AS active_3_month,
        COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM subscriptions s
                WHERE s.customer_id = c.customer_id
                  AND s.subscription_start_date
                      <= c.cohort_month + INTERVAL '6 months'
                  AND (
                      s.subscription_end_date IS NULL
                      OR s.subscription_end_date
                         >= c.cohort_month + INTERVAL '6 months'
                  )
            )
        ) AS active_6_month
    FROM cohorts c
    GROUP BY c.cohort_month
)
SELECT
    cohort_month,
    ROUND(100.0 * active_1_month / cohort_size, 2) AS retention_1_month,
    ROUND(100.0 * active_3_month / cohort_size, 2) AS retention_3_month,
    ROUND(100.0 * active_6_month / cohort_size, 2) AS retention_6_month
FROM cohort_activity
ORDER BY cohort_month;

-- Q21. Using DENSE_RANK(), rank countries by churn rate (highest to lowest) and return only the top 5.
WITH country_churn AS (
    SELECT
        c.country,
        COUNT(*) AS total_customers,
        COUNT(*) FILTER (WHERE cl.churned = TRUE) AS churned_customers
    FROM customers c
    JOIN churn_labels cl
        ON c.customer_id = cl.customer_id
    GROUP BY c.country
),
ranked AS (
    SELECT
        country,
        ROUND(
            100.0 * churned_customers / total_customers,
            2
        ) AS churn_rate,
        DENSE_RANK() OVER (
            ORDER BY churned_customers::numeric / total_customers DESC
        ) AS country_rank
    FROM country_churn
)
SELECT *
FROM ranked
WHERE country_rank <= 5
ORDER BY country_rank;

-- Q22. For every customer, compute a running total of payments made, ordered by payment_date.
SELECT
    customer_id,
    payment_date,
    amount,
    SUM(amount) OVER (
        PARTITION BY customer_id
        ORDER BY payment_date
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_total_payments
FROM payments
WHERE payment_status = 'Success'
ORDER BY customer_id, payment_date;

-- Q23. Identify customers whose watch time declined for three consecutive months.
WITH monthly_watch AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', viewing_date)::date AS month,
        SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY customer_id, month
),
lagged AS (
    SELECT
        *,
        LAG(watch_minutes, 1) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS previous_month,
        LAG(watch_minutes, 2) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS two_months_before
    FROM monthly_watch
)
SELECT *
FROM lagged
WHERE watch_minutes < previous_month
  AND previous_month < two_months_before;

-- Q24. Calculate the monthly churn rate over the last 12 months.
-- churn rate for month X = customers who churned in X / customers still active on the 1st of X
WITH anchor AS (
    SELECT DATE_TRUNC('month', MAX(churn_date))::date AS last_month FROM churn_labels
),
months AS (
    SELECT GENERATE_SERIES(a.last_month - INTERVAL '11 months', a.last_month, INTERVAL '1 month')::date AS month_start
    FROM anchor a
)
SELECT
    m.month_start AS month,
    COUNT(*) AS active_at_start,
    COUNT(*) FILTER (
        WHERE cl.churned
          AND cl.churn_date >= m.month_start
          AND cl.churn_date <  m.month_start + INTERVAL '1 month'
    ) AS churned_customers,
    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE cl.churned
              AND cl.churn_date >= m.month_start
              AND cl.churn_date <  m.month_start + INTERVAL '1 month'
        ) / NULLIF(COUNT(*), 0),
        2
    ) AS monthly_churn_rate
FROM months m
JOIN customers c
    ON c.registration_date < m.month_start
JOIN churn_labels cl
    ON cl.customer_id = c.customer_id
WHERE cl.churned = FALSE
   OR cl.churn_date >= m.month_start
GROUP BY m.month_start
ORDER BY m.month_start;

-- Q25. Calculate customer retention rate by acquisition_channel.
SELECT
    c.acquisition_channel,
    COUNT(*) AS total_customers,
    COUNT(*) FILTER (WHERE cl.churned = FALSE) AS active_customers,
    ROUND(
        100.0 *
        COUNT(*) FILTER (WHERE cl.churned = FALSE)
        / COUNT(*),
        2
    ) AS retention_rate
FROM customers c
JOIN churn_labels cl
    ON c.customer_id = cl.customer_id
GROUP BY c.acquisition_channel
ORDER BY retention_rate DESC;

-- Q26. Compute each customer's total lifetime spend and rank customers into quartiles using NTILE(4).
WITH lifetime_spend AS (
    SELECT
        c.customer_id,
        COALESCE(
            SUM(p.amount) FILTER (
                WHERE p.payment_status = 'Success'
            ), 0
        ) AS lifetime_spend
    FROM customers c
    LEFT JOIN payments p
        ON c.customer_id = p.customer_id
    GROUP BY c.customer_id
)
SELECT
    customer_id,
    lifetime_spend,
    NTILE(4) OVER (
        ORDER BY lifetime_spend
    ) AS spend_quartile
FROM lifetime_spend
ORDER BY lifetime_spend DESC;

