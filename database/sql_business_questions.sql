-- Q1. How many active customers does the platform currently have, by country?
SELECT
    c.country,
    COUNT(DISTINCT c.customer_id) AS active_customers
FROM customers c
JOIN subscriptions s
    ON c.customer_id = s.customer_id
WHERE s.subscription_status = 'Active'
GROUP BY c.country
ORDER BY active_customers DESC;

-- Q2. What is the total and average monthly revenue generated by each subscription plan?
SELECT
    sp.plan_name,
    SUM(s.monthly_price) AS total_monthly_revenue,
    ROUND(AVG(s.monthly_price), 2) AS average_monthly_revenue
FROM subscriptions s
JOIN subscription_plans sp
    ON s.plan_id = sp.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY sp.plan_name
ORDER BY total_monthly_revenue DESC;

-- Q3. What is the overall churn rate (percentage of customers with churned = true)?
SELECT
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE churned = TRUE)
        / COUNT(*),
        2
    ) AS churn_rate_percentage
FROM churn_labels;

-- Q4. Which acquisition channel has brought in the most customers, and what is the churn rate for each channel?
SELECT
    c.acquisition_channel,
    COUNT(DISTINCT c.customer_id) AS total_customers,
    ROUND(
        100.0 *
        COUNT(DISTINCT CASE WHEN cl.churned THEN c.customer_id END)
        / COUNT(DISTINCT c.customer_id),
        2
    ) AS churn_rate_percentage
FROM customers c
LEFT JOIN churn_labels cl
    ON c.customer_id = cl.customer_id
GROUP BY c.acquisition_channel
ORDER BY total_customers DESC;

-- Q5. What is the average customer age by subscription plan?
SELECT
    sp.plan_name,
    ROUND(AVG(c.age), 2) AS average_customer_age
FROM customers c
JOIN subscriptions s
    ON c.customer_id = s.customer_id
JOIN subscription_plans sp
    ON s.plan_id = sp.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY sp.plan_name;

-- Q6. List the top 10 most-watched titles by total watch_duration_minutes.
SELECT
    c.title,
    SUM(v.watch_duration_minutes) AS total_watch_minutes
FROM viewing_activity v
JOIN content c
    ON v.content_id = c.content_id
GROUP BY c.content_id, c.title
ORDER BY total_watch_minutes DESC
LIMIT 10;

-- Q7. What is the average completion_percentage by content_type and genre?
SELECT
    c.content_type,
    c.genre,
    ROUND(AVG(v.completion_percentage), 2) AS average_completion_percentage
FROM viewing_activity v
JOIN content c
    ON v.content_id = c.content_id
GROUP BY c.content_type, c.genre
ORDER BY c.content_type, average_completion_percentage DESC;

-- Q8. How many failed payments occurred in each of the last 12 months?
WITH anchor AS (
    -- the dataset ends on a fixed date, so "last 12 months" is measured back from the latest payment
    SELECT DATE_TRUNC('month', MAX(payment_date))::date AS last_month
    FROM payments
)
SELECT
    DATE_TRUNC('month', p.payment_date)::date AS payment_month,
    COUNT(*) AS failed_payments
FROM payments p
CROSS JOIN anchor a
WHERE p.payment_status = 'Failed'
  AND p.payment_date >= a.last_month - INTERVAL '11 months'
GROUP BY payment_month
ORDER BY payment_month;

-- Q9. What is the average resolution_time_hours by issue_category?
