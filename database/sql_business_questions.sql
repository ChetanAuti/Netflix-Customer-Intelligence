-- Q28. Identify customers with 2+ failed payments in the last 90 days who are also flagged as high churn risk.
-- "high churn risk" = risk_tier 'High' in customer_scores (written by the churn model, src/models/train.py)
WITH anchor AS (
    SELECT MAX(payment_date) AS as_of FROM payments
),
failed_payments AS (
    SELECT
        p.customer_id,
        COUNT(*) AS failed_payment_count
    FROM payments p
    CROSS JOIN anchor a
    WHERE p.payment_status = 'Failed'
      AND p.payment_date > a.as_of - INTERVAL '90 days'
    GROUP BY p.customer_id
    HAVING COUNT(*) >= 2
)
SELECT
    fp.customer_id,
    fp.failed_payment_count,
    sp.plan_name AS current_plan
FROM failed_payments fp
JOIN customer_scores cs
    ON cs.customer_id = fp.customer_id
   AND cs.risk_tier = 'High'
JOIN subscriptions s
    ON s.customer_id = fp.customer_id
   AND s.subscription_status = 'Active'
JOIN subscription_plans sp
    ON sp.plan_id = s.plan_id
ORDER BY fp.failed_payment_count DESC;

-- Q29. Compare average customer engagement for the 30 days before and after each customer's most recent subscription price change.
WITH price_changes AS (
    SELECT
        customer_id,
        subscription_start_date AS change_date,
        monthly_price,
        LAG(monthly_price) OVER (
            PARTITION BY customer_id
            ORDER BY subscription_start_date
        ) AS previous_price
    FROM subscriptions
),
changes AS (
    SELECT *
    FROM price_changes
    WHERE previous_price IS NOT NULL
      AND monthly_price <> previous_price
),
engagement AS (
    SELECT
        pc.customer_id,
        pc.change_date,
        AVG(v.watch_duration_minutes)
            FILTER (
                WHERE v.viewing_date >= pc.change_date - INTERVAL '30 days'
                  AND v.viewing_date < pc.change_date
            ) AS before_avg,
        AVG(v.watch_duration_minutes)
            FILTER (
                WHERE v.viewing_date > pc.change_date
                  AND v.viewing_date <= pc.change_date + INTERVAL '30 days'
            ) AS after_avg
    FROM changes pc
    LEFT JOIN viewing_activity v
        ON pc.customer_id = v.customer_id
    GROUP BY pc.customer_id, pc.change_date
)
SELECT
    customer_id,
    change_date,
    ROUND(before_avg, 2) AS before_avg,
    ROUND(after_avg, 2) AS after_avg,
    ROUND(
        100.0 * (after_avg - before_avg)
        / NULLIF(before_avg, 0),
        2
    ) AS percentage_change
FROM engagement;

-- Q30. For each country: total customers, churned customers, churn rate, average customer lifetime value, and top 1 churn_reason.
WITH lifetime_value AS (
    SELECT
        customer_id,
        SUM(amount) AS lifetime_value
    FROM payments
    WHERE payment_status = 'Success'
    GROUP BY customer_id
),
country_data AS (
    SELECT
        c.country,
        COUNT(*) AS total_customers,
        COUNT(*) FILTER (WHERE cl.churned) AS churned_customers,
        AVG(
            CASE
                WHEN cl.churned THEN lv.lifetime_value
            END
        ) AS avg_churned_ltv
    FROM customers c
    LEFT JOIN churn_labels cl
        ON c.customer_id = cl.customer_id
    LEFT JOIN lifetime_value lv
        ON c.customer_id = lv.customer_id
    GROUP BY c.country
),
reasons AS (
    SELECT
        c.country,
        cl.churn_reason,
        ROW_NUMBER() OVER (
            PARTITION BY c.country
            ORDER BY COUNT(*) DESC
        ) AS rn
    FROM customers c
    JOIN churn_labels cl
        ON c.customer_id = cl.customer_id
    WHERE cl.churned = TRUE
    GROUP BY c.country, cl.churn_reason
)
SELECT
    cd.country,
    cd.total_customers,
    cd.churned_customers,
    ROUND(
        100.0 * cd.churned_customers
        / NULLIF(cd.total_customers, 0),
        2
    ) AS churn_rate,
    ROUND(cd.avg_churned_ltv, 2) AS avg_customer_lifetime_value,
    r.churn_reason AS top_churn_reason
FROM country_data cd
LEFT JOIN reasons r
    ON cd.country = r.country
   AND r.rn = 1
ORDER BY churn_rate DESC;

-- Q31. Build an "at-risk revenue" report for currently active customers (top 50).
WITH activity AS (
    SELECT
        customer_id,
        (SELECT MAX(viewing_date) FROM viewing_activity) - MAX(viewing_date) AS days_since_last_activity
    FROM viewing_activity
    GROUP BY customer_id
),
payment_stats AS (
    SELECT
        customer_id,
        COUNT(*) FILTER (WHERE payment_status = 'Failed')::numeric
        / NULLIF(COUNT(*), 0) AS failed_payment_rate
    FROM payments
    GROUP BY customer_id
),
tickets AS (
    SELECT
        customer_id,
        COUNT(*) AS support_ticket_count
    FROM support_tickets
    GROUP BY customer_id
),
scored AS (
    SELECT
        c.customer_id,
        s.monthly_price,
        COALESCE(a.days_since_last_activity, 9999) AS days_since_last_activity,
        COALESCE(p.failed_payment_rate, 0) AS failed_payment_rate,
        COALESCE(t.support_ticket_count, 0) AS support_ticket_count
    FROM customers c
    JOIN subscriptions s
        ON c.customer_id = s.customer_id
       AND s.subscription_status = 'Active'
    LEFT JOIN activity a
        ON c.customer_id = a.customer_id
    LEFT JOIN payment_stats p
        ON c.customer_id = p.customer_id
    LEFT JOIN tickets t
        ON c.customer_id = t.customer_id
)
SELECT
    customer_id,
    monthly_price,
    ROUND(
        (
            LEAST(days_since_last_activity / 90.0, 1) * 0.4
            + failed_payment_rate * 0.3
            + LEAST(support_ticket_count / 10.0, 1) * 0.3
        )::numeric,
        4
    ) AS risk_score,
    ROUND(
        (
            (
                LEAST(days_since_last_activity / 90.0, 1) * 0.4
                + failed_payment_rate * 0.3
                + LEAST(support_ticket_count / 10.0, 1) * 0.3
            ) * monthly_price
        )::numeric,
        2
    ) AS at_risk_revenue
FROM scored
ORDER BY at_risk_revenue DESC
LIMIT 50;

-- Q32. Identify the top 5 customer complaints per country for the most recent completed quarter.
WITH latest_quarter AS (
    SELECT
        DATE_TRUNC('quarter', MAX(ticket_date))
        - INTERVAL '3 months' AS quarter_start
    FROM support_tickets
    WHERE ticket_date IS NOT NULL
),
complaints AS (
    SELECT
        c.country,
        st.issue_subcategory,
        COUNT(*) AS complaint_count,
        AVG(st.resolution_time_hours) AS avg_resolution_time,
        AVG(st.customer_satisfaction_score) AS avg_satisfaction
    FROM support_tickets st
    JOIN customers c
        ON st.customer_id = c.customer_id
    CROSS JOIN latest_quarter q
    WHERE st.ticket_date >= q.quarter_start
      AND st.ticket_date < q.quarter_start + INTERVAL '3 months'
    GROUP BY c.country, st.issue_subcategory
),
ranked AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY country
            ORDER BY complaint_count DESC
        ) AS rn
    FROM complaints
)
SELECT
    country,
    issue_subcategory,
    complaint_count,
    ROUND(avg_resolution_time, 2) AS avg_resolution_time,
    ROUND(avg_satisfaction, 2) AS avg_satisfaction
FROM ranked
WHERE rn <= 5
ORDER BY country, complaint_count DESC;

-- Q33. Identify "win-back" candidates: churned customers with customer_lifetime_value in the top quartile.
WITH lifetime_value AS (
    SELECT
        customer_id,
        SUM(amount) AS customer_lifetime_value
    FROM payments
    WHERE payment_status = 'Success'
    GROUP BY customer_id
),
quartiles AS (
    SELECT
        customer_id,
        customer_lifetime_value,
        NTILE(4) OVER (
            ORDER BY customer_lifetime_value
        ) AS ltv_quartile
    FROM lifetime_value
),
engagement AS (
    SELECT
        customer_id,
        AVG(watch_duration_minutes) AS avg_watch_duration
    FROM viewing_activity
    GROUP BY customer_id
)
SELECT
    c.customer_id,
    cl.churn_reason,
    q.customer_lifetime_value,
    e.avg_watch_duration AS last_known_engagement
FROM customers c
JOIN churn_labels cl
    ON c.customer_id = cl.customer_id
JOIN quartiles q
    ON c.customer_id = q.customer_id
LEFT JOIN engagement e
    ON c.customer_id = e.customer_id
WHERE cl.churned = TRUE
  AND q.ltv_quartile = 4
ORDER BY q.customer_lifetime_value DESC;

-- Q34. Build a plan-migration analysis: most common migration path, and upgrader vs downgrader churn.
-- (a) most common migration path (consecutive plan changes only; same-plan renewals are ignored)
WITH seg AS (
    SELECT
        s.customer_id,
        s.plan_id,
        sp.plan_name,
        LEAD(s.plan_id)   OVER w AS next_plan_id,
        LEAD(sp.plan_name) OVER w AS next_plan_name
    FROM subscriptions s
    JOIN subscription_plans sp
        ON sp.plan_id = s.plan_id
    WINDOW w AS (PARTITION BY s.customer_id ORDER BY s.subscription_start_date)
)
SELECT
    plan_name      AS from_plan,
    next_plan_name AS to_plan,
    COUNT(*)       AS migration_count,
    RANK() OVER (ORDER BY COUNT(*) DESC) AS popularity_rank
FROM seg
WHERE next_plan_id IS NOT NULL
  AND next_plan_id <> plan_id
GROUP BY plan_name, next_plan_name
ORDER BY migration_count DESC;

-- (b) do upgraders churn at a different rate than downgraders (vs. customers who never changed plan)?
WITH seg AS (
    SELECT
        s.customer_id,
        s.subscription_start_date,
        sp.monthly_price AS list_price,
        LEAD(sp.monthly_price) OVER w AS next_list_price,
        LEAD(s.plan_id)        OVER w AS next_plan_id,
        s.plan_id
    FROM subscriptions s
    JOIN subscription_plans sp
        ON sp.plan_id = s.plan_id
    WINDOW w AS (PARTITION BY s.customer_id ORDER BY s.subscription_start_date)
),
latest_change AS (
    SELECT DISTINCT ON (customer_id)
        customer_id,
        CASE WHEN next_list_price > list_price THEN 'Upgrade' ELSE 'Downgrade' END AS migration_type
    FROM seg
    WHERE next_plan_id IS NOT NULL
      AND next_plan_id <> plan_id
    ORDER BY customer_id, subscription_start_date DESC
)
SELECT
    COALESCE(lc.migration_type, 'No plan change') AS migration_type,
    COUNT(*) AS customers,
    COUNT(*) FILTER (WHERE cl.churned) AS churned_customers,
    ROUND(100.0 * COUNT(*) FILTER (WHERE cl.churned) / COUNT(*), 2) AS churn_rate_pct
FROM churn_labels cl
LEFT JOIN latest_change lc
    ON lc.customer_id = cl.customer_id
GROUP BY COALESCE(lc.migration_type, 'No plan change')
ORDER BY churn_rate_pct DESC;

-- Q35. Calculate weekly active users (WAU), monthly active users (MAU), and WAU/MAU stickiness over the last 6 months.
WITH weekly AS (
    SELECT
        DATE_TRUNC('week', viewing_date)::date AS week,
        COUNT(DISTINCT customer_id) AS wau
    FROM viewing_activity
    WHERE viewing_date >= (SELECT DATE_TRUNC('month', MAX(viewing_date)) - INTERVAL '5 months' FROM viewing_activity)
    GROUP BY week
),
monthly AS (
    SELECT
        DATE_TRUNC('month', viewing_date)::date AS month,
        COUNT(DISTINCT customer_id) AS mau
    FROM viewing_activity
    WHERE viewing_date >= (SELECT DATE_TRUNC('month', MAX(viewing_date)) - INTERVAL '5 months' FROM viewing_activity)
    GROUP BY month
)
SELECT
    m.month,
    m.mau,
    ROUND(AVG(w.wau), 2) AS avg_weekly_active_users,
    ROUND(
        AVG(w.wau) / NULLIF(m.mau, 0),
        4
    ) AS wau_mau_stickiness
FROM monthly m
LEFT JOIN weekly w
    ON w.week >= m.month
   AND w.week < m.month + INTERVAL '1 month'
GROUP BY m.month, m.mau
ORDER BY m.month;

-- Q36. Identify customers who submitted negative feedback within 14 days of a failed payment or a low-satisfaction support ticket.
WITH negative_feedback AS (
    SELECT
        customer_id,
        feedback_date
    FROM customer_feedback
    WHERE rating <= 2
),
failed_payments AS (
    SELECT
        customer_id,
        payment_date
    FROM payments
    WHERE payment_status = 'Failed'
),
bad_tickets AS (
    SELECT
        customer_id,
        ticket_date
    FROM support_tickets
    WHERE customer_satisfaction_score <= 2
)
SELECT DISTINCT
    nf.customer_id,
    nf.feedback_date
FROM negative_feedback nf
WHERE EXISTS (
    SELECT 1
    FROM failed_payments fp
    WHERE fp.customer_id = nf.customer_id
      AND ABS(nf.feedback_date - fp.payment_date) <= 14
)
OR EXISTS (
    SELECT 1
    FROM bad_tickets bt
    WHERE bt.customer_id = nf.customer_id
      AND ABS(nf.feedback_date - bt.ticket_date) <= 14
)
ORDER BY nf.customer_id;

-- Q37. Build a full "customer health score" query combining recency, payment failure rate, support satisfaction, tenure, and current plan.
WITH activity AS (
    SELECT
        customer_id,
        (SELECT MAX(viewing_date) FROM viewing_activity) - MAX(viewing_date) AS days_since_last_viewing
    FROM viewing_activity
    GROUP BY customer_id
),
payment_stats AS (
    SELECT
        customer_id,
        COUNT(*) FILTER (WHERE payment_status = 'Failed')::numeric
        / NULLIF(COUNT(*), 0) AS failure_rate
    FROM payments
    GROUP BY customer_id
),
support_stats AS (
    SELECT
        customer_id,
        AVG(customer_satisfaction_score) AS avg_satisfaction
    FROM support_tickets
    WHERE customer_satisfaction_score IS NOT NULL
    GROUP BY customer_id
)
SELECT
    c.customer_id,
    sp.plan_name,
    COALESCE(a.days_since_last_viewing, 9999) AS days_since_last_viewing,
    COALESCE(p.failure_rate, 0) AS payment_failure_rate,
    COALESCE(s.avg_satisfaction, 0) AS avg_support_satisfaction,
    (SELECT MAX(viewing_date) FROM viewing_activity) - c.registration_date AS tenure_days,
    ROUND(
        (
            LEAST(COALESCE(a.days_since_last_viewing, 9999) / 90.0, 1) * 40
            + COALESCE(p.failure_rate, 0) * 30
            + (1 - LEAST(COALESCE(s.avg_satisfaction, 0) / 5.0, 1)) * 20
            + (1 - LEAST(
                ((SELECT MAX(viewing_date) FROM viewing_activity) - c.registration_date) / 365.0, 1
              )) * 10
        )::numeric,
        2
    ) AS risk_score
FROM customers c
LEFT JOIN activity a
    ON c.customer_id = a.customer_id
LEFT JOIN payment_stats p
    ON c.customer_id = p.customer_id
LEFT JOIN support_stats s
    ON c.customer_id = s.customer_id
LEFT JOIN subscriptions sub
    ON c.customer_id = sub.customer_id
   AND sub.subscription_status = 'Active'
LEFT JOIN subscription_plans sp
    ON sub.plan_id = sp.plan_id
ORDER BY risk_score DESC;
