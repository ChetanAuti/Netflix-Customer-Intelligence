"""Generate the 6 notebooks (thin, readable wrappers around src/): python build_notebooks.py"""
import json
from pathlib import Path

OUT = Path(__file__).parent / "notebooks"
OUT.mkdir(exist_ok=True)
SETUP = "import sys; sys.path.insert(0, '..')\nimport pandas as pd, json\nfrom IPython.display import Image, display, Markdown\npd.set_option('display.width', 140)"


def nb(name, cells):
    out = []
    for kind, text in cells:
        out.append({"cell_type": kind, "metadata": {}, "source": text.splitlines(True),
                    **({"outputs": [], "execution_count": None} if kind == "code" else {})})
    (OUT / name).write_text(json.dumps({"cells": out, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}}, "nbformat": 4, "nbformat_minor": 5}, indent=1))


